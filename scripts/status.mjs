#!/usr/bin/env node
/**
 * The status ledger — STATUS.md as event sourcing: an append-only log of what happened, and the
 * "current state" as a projection folded from that log. ONE file, and every text lives once.
 *
 *   node scripts/status.mjs record <event> <key> "<what>" [--evidence "…"] [--author "…"]
 *   node scripts/status.mjs sync                  ingest the events the gate left in the journal
 *   node scripts/status.mjs rebuild [--reseq]     replay the log → regenerate the projection
 *   node scripts/status.mjs check                 gate signal: ledger well formed, projection = replay,
 *                                                 every gotcha recorded; obsolete/stale as warnings
 *   node scripts/status.mjs log [--event e] [--key k] [--author a] [--since YYYY-MM-DD]
 *   node scripts/status.mjs migrate [--apply]     legacy STATUS.md (prose + tables) → ledger (dry-run)
 *
 * Why a ledger: STATUS.md was edited in place, so "verde" had no author, no date per line and no
 * history — a row could be rewritten and nobody could tell what it said before or who verified it.
 * Now every change is a row with seq, timestamp, author, event, key, what happened and evidence;
 * the top of the file is DERIVED (`rebuild`) and `check` fails if someone edits it by hand.
 *
 * No text is written twice. The projection is an INDEX — verdict word, `#seq` and date per signal,
 * the title per debt item — and the full text stays in its log row (`log --key` shows it). A
 * gotcha's text stays in the incident register: its event carries the title and a pointer.
 *
 * The gate never writes STATUS.md (P7, and a tracked file changed by the gate would turn the
 * task-scope signal red on the next run). It appends to a journal under `.git/` when the verdict
 * CHANGES, and `sync` (or any `record`) moves those events into the ledger.
 *
 * Everything specific comes from `status` in the config (`status.events` turns this on). Without
 * it the script does nothing.
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { REPO_ROOT, CONFIG_PATH, rutaDeEstado, isoLocal, DEFAULT_STATUS_JOURNAL } from "../.claude/hooks/harness.mjs";
import { leerGotchas, rutasCitadas, seccionesDe, tablaDe, vinetasDe, sinMarcas, specDelPanel } from "./panel/leer-fuentes.mjs";

let config;
try {
  config = JSON.parse(fs.readFileSync(CONFIG_PATH, "utf8"));
} catch {
  console.log("status: no readable config — nothing to do.");
  process.exit(0);
}
const spec = config.status?.events;
if (!spec) {
  console.log("status: `status.events` is not declared — the ledger is off.");
  process.exit(0);
}

const STATUS_FILE = path.join(REPO_ROOT, config.status.file ?? "STATUS.md");
const STATUS_REL = path.relative(REPO_ROOT, STATUS_FILE).split(path.sep).join("/");
const JOURNAL = rutaDeEstado(spec.journal ?? DEFAULT_STATUS_JOURNAL);
const STALE_DAYS = Number.isInteger(spec.staleDays) ? spec.staleDays : (config.drift?.statusMaxAgeDays ?? 30);
const INCIDENTS_FILE = config.incidents?.file ?? null;

// Header fields and section titles are the ones the panel already reads (`panel.status`): one
// truth, not two. `check` fails if a label here stops matching the panel's section pattern.
const PANEL_STATUS = specDelPanel(config).status;
const FIELDS = PANEL_STATUS.fields;
const SECTIONS = PANEL_STATUS.sections;
const LABELS = {
  lastEvent: "Último evento",
  signals: "Señales",
  debt: "Deuda conocida",
  log: "Bitácora",
  noVerdict: "sin veredicto registrado",
  noDebt: "(ninguna registrada)",
  detail: "el detalle de cada fila está en su evento de la bitácora: `node scripts/status.mjs log --key \"<clave>\"`",
  migrated: (n, from, inc) => `${n} eventos importados del ${from} anterior (texto en prosa) y de ${inc}; timestamp y autor de cada uno salen de \`git blame\` de su línea`,
  signalColumns: ["Señal", "Comando", "Último resultado"],
  logColumns: ["#", "Timestamp", "Autor", "Evento", "Clave", "Qué pasó", "Evidencia"],
  ...(spec.labels ?? {}),
};
const BEGIN = "<!-- status:projection:begin — generated by `node scripts/status.mjs rebuild` from the log below; do not edit by hand -->";
const END = "<!-- status:projection:end -->";
const LOG_NOTE = "<!-- status:log — append-only. Add rows with `node scripts/status.mjs record`, never by hand. -->";

/**
 * The closed vocabulary. `closes` = this event ends what the other one opened (same key);
 * closing a key that is not open is an error, because the ledger would be lying about history.
 * `pointer` = the text lives elsewhere (the incident register): «what» may stay empty.
 */
const EVENTS = {
  "gate.verdict": { key: true },
  "signal.verified": { key: true },
  "signal.retired": { key: true, closes: "signal.verified" },
  "debt.opened": { key: true },
  "debt.closed": { key: true, closes: "debt.opened" },
  "incident.recorded": { key: true, pointer: true },
  "incident.retired": { key: true, closes: "incident.recorded" },
  note: { key: false },
};

// ── small helpers ───────────────────────────────────────────────────────────

const [cmd, ...rest] = process.argv.slice(2);
const option = (name) => {
  const i = rest.indexOf(name);
  return i >= 0 && rest[i + 1] !== undefined && !rest[i + 1].startsWith("--") ? rest[i + 1] : null;
};
const flag = (name) => rest.includes(name);
const positionals = () => {
  const out = [];
  for (let i = 0; i < rest.length; i++) {
    if (rest[i].startsWith("--")) {
      if (rest[i + 1] !== undefined && !rest[i + 1].startsWith("--") && !["--apply", "--reseq"].includes(rest[i])) i++;
      continue;
    }
    out.push(rest[i]);
  }
  return out;
};
const die = (msg) => {
  console.error(`status: ${msg}`);
  process.exit(1);
};
const git = (...args) => {
  const r = spawnSync("git", args, { cwd: REPO_ROOT, encoding: "utf8", windowsHide: true, maxBuffer: 64 * 1024 * 1024 });
  return r.status === 0 ? r.stdout : null;
};
const read = (f) => {
  try {
    return fs.readFileSync(f, "utf8");
  } catch {
    return null;
  }
};

/** Order by the instant, not by the text: two authors in different offsets sort wrong as strings. */
const byTime = (a, b) => Date.parse(a.ts) - Date.parse(b.ts);
const defaultAuthor = () => (git("config", "user.name") ?? "").trim() || os.userInfo().username || "unknown";

/** A table cell: one line, `|` escaped. Already-escaped pipes stay as they are. */
const cell = (s) =>
  String(s ?? "")
    .replace(/\r?\n+/g, " ")
    .replace(/(?<!\\)\|/g, "\\|")
    .trim();
const unescapeCell = (s) => String(s ?? "").replace(/\\\|/g, "|");
const row = (cells) => `| ${cells.join(" | ")} |`;
const sepRow = (n) => `|${"---|".repeat(n)}`;

/**
 * The verdict of a result, without its explanation: «verde — 27 casos…» → «verde». The lead
 * before « — » when it is short, else the first word. The panel colors a row by that word.
 */
const verdictOf = (what) => {
  const plain = sinMarcas(what);
  const lead = plain.split(" — ")[0];
  return lead.length <= 32 ? lead : plain.split(/\s/)[0];
};

// ── the log: parse and render ───────────────────────────────────────────────

/** Rows of the ledger table, with their line numbers. */
function parseLog(text) {
  const lines = text.split("\n");
  const head = row(LABELS.logColumns);
  const start = lines.findIndex((l) => l.trim() === head);
  if (start === -1) return { found: false, events: [], problems: [] };
  const events = [];
  const problems = [];
  for (let i = start + 2; i < lines.length; i++) {
    const l = lines[i];
    if (!/^\s*\|/.test(l)) break;
    const cells = l.trim().replace(/^\||\|$/g, "").split(/(?<!\\)\|/).map((c) => c.trim());
    if (cells.length !== LABELS.logColumns.length) {
      problems.push({ line: i + 1, msg: `row has ${cells.length} cells, the log has ${LABELS.logColumns.length}` });
      continue;
    }
    // Unescaped inside: a key is compared with gotcha titles and CLI input, which carry a bare `|`.
    const [seq, ts, author, event, key, what, evidence] = cells.map(unescapeCell);
    const blank = (s) => (s === "—" ? "" : s);
    events.push({ seq: Number(seq), ts, author, event, key: blank(key), what: blank(what), evidence: blank(evidence), line: i + 1 });
  }
  return { found: true, events, problems };
}

const logRow = (e) => row([e.seq, e.ts, cell(e.author), e.event, cell(e.key) || "—", cell(e.what) || "—", cell(e.evidence) || "—"]);
const logTable = (events) => [row(LABELS.logColumns), sepRow(LABELS.logColumns.length), ...events.map(logRow)].join("\n");

// ── the projection: fold the events ─────────────────────────────────────────

function fold(events) {
  const state = { verdict: null, signals: new Map(), debt: new Map(), incidents: new Map(), last: null };
  for (const e of events) {
    state.last = e;
    if (e.event === "gate.verdict") state.verdict = e;
    else if (e.event === "signal.verified") state.signals.set(e.key, e);
    else if (e.event === "signal.retired") state.signals.delete(e.key);
    else if (e.event === "debt.opened") state.debt.set(e.key, e);
    else if (e.event === "debt.closed") state.debt.delete(e.key);
    else if (e.event === "incident.recorded") state.incidents.set(e.key, e);
    else if (e.event === "incident.retired") state.incidents.delete(e.key);
  }
  return state;
}

/**
 * The projection is an index, not a copy: the header, the debt titles (short, and first so they
 * fit in the 40 lines the session hook reads) and one line per signal with its verdict word and
 * the `#seq` that holds the full text.
 */
function renderProjection(state) {
  const v = state.verdict;
  const head = v ? /@\s*([0-9a-f]{6,40})/i.exec(v.evidence)?.[1] : null;
  const gateCmd = config.gate?.command ?? "gate";
  const out = [BEGIN, ""];
  out.push(`- **${FIELDS.date}:** ${v ? v.ts.slice(0, 10) : "—"}`);
  out.push(`- **${FIELDS.branch}:** ${v ? `\`${v.key}\`${head ? ` (${head})` : ""}` : "—"}`);
  out.push(`- **${FIELDS.verdict}:** ${v ? `${verdictOf(v.what)} (\`${gateCmd}\`) · #${v.seq}` : LABELS.noVerdict}`);
  if (state.last) out.push(`- **${LABELS.lastEvent}:** #${state.last.seq} · ${state.last.ts} · ${state.last.author} · \`${state.last.event}\``);
  out.push("", `## ${LABELS.debt}`, "");
  if (!state.debt.size) out.push(`- ${LABELS.noDebt}`);
  for (const [key, e] of state.debt) out.push(`- **${key}** · #${e.seq} · ${e.ts.slice(0, 10)}`);
  out.push("", `## ${LABELS.signals}`, "", `<!-- ${LABELS.detail} -->`, "");
  out.push(row(LABELS.signalColumns), sepRow(LABELS.signalColumns.length));
  for (const [key, e] of state.signals) out.push(row([cell(key), cell(e.evidence) || "—", `${cell(verdictOf(e.what))} · #${e.seq} · ${e.ts.slice(0, 10)}`]));
  out.push("", END);
  return out.join("\n");
}

// ── the file: head (human) · projection (derived) · log (append-only) ───────

function loadStatus() {
  const text = read(STATUS_FILE);
  if (text === null) die(`${STATUS_REL} does not exist. Start it with \`node scripts/status.mjs migrate --apply\`.`);
  const b = text.indexOf(BEGIN);
  const e = text.indexOf(END);
  return {
    text,
    hasMarkers: b !== -1 && e > b,
    head: b === -1 ? text.split(/^## /m)[0].trimEnd() : text.slice(0, b).trimEnd(),
    projection: b !== -1 && e > b ? text.slice(b, e + END.length) : null,
    ...parseLog(text),
  };
}
/**
 * The status file as a LEDGER, or stop. Every command that writes goes through here: on a STATUS.md
 * still in prose, `sync` or `rebuild` would rewrite everything below the first `##` without a
 * dry-run (P9). Only `migrate` turns prose into a ledger. Found by the reviewer.
 */
function loadLedger() {
  const st = loadStatus();
  if (!st.found || !st.hasMarkers)
    die(`${STATUS_REL} is not a ledger yet (no projection markers or no log table) — nothing written. \`node scripts/status.mjs migrate\` shows the conversion; \`--apply\` does it.`);
  return st;
}

function writeStatus(head, events, { fresh = false } = {}) {
  // Second lock behind `loadLedger`: no path other than `migrate` overwrites a prose STATUS.md.
  const current = read(STATUS_FILE);
  if (!fresh && current !== null && !current.includes(BEGIN)) die(`${STATUS_REL} is prose, not a ledger — refusing to overwrite it. \`migrate\` first.`);
  fs.writeFileSync(STATUS_FILE, [head, "", renderProjection(fold(events)), "", `## ${LABELS.log}`, "", LOG_NOTE, "", logTable(events), ""].join("\n"));
}

// ── the journal the gate writes (.git/, P7) ─────────────────────────────────

// `ingest` first RENAMES the journal (atomic) and reads the claimed copy: a gate that appends while
// the ledger is being written lands in a fresh journal instead of being erased with the old one.
// A claimed copy left by a failed write is read again next time.
const CLAIMED = `${JOURNAL}.ingesting`;
function claimJournal() {
  try {
    if (!fs.existsSync(JOURNAL)) return;
    if (fs.existsSync(CLAIMED)) {
      fs.appendFileSync(CLAIMED, fs.readFileSync(JOURNAL, "utf8"));
      fs.rmSync(JOURNAL, { force: true });
    } else fs.renameSync(JOURNAL, CLAIMED);
  } catch {
    /* unreadable journal: nothing claimed, nothing lost */
  }
}
function readJournal({ claimed = false } = {}) {
  const t = claimed ? read(CLAIMED) : `${read(CLAIMED) ?? ""}${read(JOURNAL) ?? ""}`;
  if (!t) return [];
  return t
    .split("\n")
    .filter(Boolean)
    .map((l) => {
      try {
        return JSON.parse(l);
      } catch {
        return null;
      }
    })
    .filter((e) => e && EVENTS[e.event]);
}

const lastSeq = (events) => Math.max(0, ...events.map((e) => e.seq).filter(Number.isFinite));
/** Move pending journal events into the log. Returns how many. */
function ingest(st) {
  claimJournal();
  const pending = readJournal({ claimed: true }).sort(byTime);
  let seq = lastSeq(st.events);
  for (const p of pending) st.events.push({ seq: ++seq, ts: p.ts, author: p.author ?? "gate", event: p.event, key: p.key ?? "", what: p.what ?? "", evidence: p.evidence ?? "" });
  return pending.length;
}
const clearJournal = () => {
  try {
    fs.rmSync(CLAIMED, { force: true });
  } catch {
    /* a journal that cannot be cleared is ingested twice: check reports the duplicates */
  }
};

// ── validation (the debugging half) ─────────────────────────────────────────

function validate(st, { gotchasText, trackedFiles, today = new Date() }) {
  const errors = [];
  const warnings = [];
  const all = st.events;
  const where = (e) => (e.line ? `${STATUS_REL}:${e.line}` : `#${e.seq}`);

  if (!st.found) errors.push(`${STATUS_REL}: no log table (header \`${row(LABELS.logColumns)}\`). Run \`node scripts/status.mjs migrate\`.`);
  if (!st.hasMarkers) errors.push(`${STATUS_REL}: projection markers missing — run \`node scripts/status.mjs migrate\` (prose) or \`rebuild\` (ledger).`);
  for (const p of st.problems) errors.push(`${STATUS_REL}:${p.line}: ${p.msg}.`);

  const open = { "signal.verified": new Set(), "debt.opened": new Set(), "incident.recorded": new Set() };
  let prev = null;
  const seen = new Set();
  for (const e of all) {
    if (!Number.isInteger(e.seq)) errors.push(`${where(e)}: seq «${e.seq}» is not a number.`);
    else if (seen.has(e.seq)) errors.push(`${where(e)}: seq #${e.seq} is duplicated (a merge of two branches?) — \`node scripts/status.mjs rebuild --reseq\`.`);
    else if (prev && e.seq !== prev.seq + 1) errors.push(`${where(e)}: seq jumps from #${prev.seq} to #${e.seq} — events missing from the log.`);
    seen.add(e.seq);
    if (Number.isNaN(Date.parse(e.ts)) || !/^\d{4}-\d{2}-\d{2}T/.test(e.ts)) errors.push(`${where(e)}: timestamp «${e.ts}» is not ISO 8601.`);
    else if (prev && Date.parse(e.ts) < Date.parse(prev.ts)) warnings.push(`${where(e)}: #${e.seq} happened before #${prev.seq} (${e.ts} < ${prev.ts}): recorded late. The seq is the order of record.`);
    if (!e.author) errors.push(`${where(e)}: #${e.seq} has no author.`);
    const def = EVENTS[e.event];
    if (!def) {
      errors.push(`${where(e)}: unknown event «${e.event}». Known: ${Object.keys(EVENTS).join(", ")}.`);
    } else {
      if (def.key && !e.key) errors.push(`${where(e)}: \`${e.event}\` needs a key.`);
      if (def.closes) {
        if (!open[def.closes].has(e.key)) errors.push(`${where(e)}: \`${e.event}\` closes «${e.key}», which is not open.`);
        open[def.closes].delete(e.key);
      } else if (open[e.event]) open[e.event].add(e.key);
      if (!e.what && !def.pointer) warnings.push(`${where(e)}: #${e.seq} does not say what happened.`);
    }
    prev = e;
  }

  // The projection is derived: if the file differs from the replay, either someone edited it by
  // hand or the config that shapes it changed (`gate.command`, `labels`). Both fix the same way.
  if (st.hasMarkers && !errors.length && st.projection !== renderProjection(fold(all)))
    errors.push(`${STATUS_REL}: the projection does not match the replay of the log — edited by hand, or \`gate.command\`/\`status.events.labels\` changed. A hand edit goes back as an event (\`status.mjs record …\`); then \`rebuild\` regenerates it.`);
  // The panel reads the projection by its section patterns: a label that stops matching blinds it.
  for (const k of ["signals", "debt"])
    if (SECTIONS[k] && !new RegExp(SECTIONS[k], "i").test(LABELS[k])) errors.push(`label «${LABELS[k]}» does not match the panel's section pattern \`${SECTIONS[k]}\` — the panel would not read the projection. Align \`status.events.labels.${k}\` with \`panel.status.sections.${k}\`.`);

  const pending = readJournal();
  if (pending.length) warnings.push(`${pending.length} event(s) from the gate wait in the journal — \`node scripts/status.mjs sync\`.`);

  // Gotchas: every incident in the register has its event, and every recorded event its incident.
  const state = fold(all);
  if (gotchasText !== null) {
    const gotchas = leerGotchas(gotchasText, { encabezado: config.incidents?.heading ?? "### GOTCHA", campos: config.incidents?.requiredLines });
    const counted = new Map();
    for (const g of gotchas) counted.set(g.titulo, (counted.get(g.titulo) ?? 0) + 1);
    for (const [t, n] of counted) if (n > 1) errors.push(`${INCIDENTS_FILE}: gotcha «${t}» appears ${n} times.`);
    for (const t of counted.keys())
      if (!state.incidents.has(t)) errors.push(`gotcha «${t}» has no \`incident.recorded\` event — \`node scripts/status.mjs record incident.recorded "${t}" --evidence "${INCIDENTS_FILE}"\`.`);
    for (const k of state.incidents.keys())
      if (!counted.has(k)) errors.push(`incident «${k}» is recorded but ${INCIDENTS_FILE} no longer has it (renamed or removed?) — \`record incident.retired "${k}" "<why>"\`.`);
    // The rule is the field before the mechanism in `incidents.requiredLines` (Síntoma, Causa, REGLA, Mecanismo).
    const ruleField = String(config.incidents?.requiredLines?.at(-2) ?? "").replace(/:$/, "");
    const rules = new Map();
    for (const g of gotchas) {
      const regla = sinMarcas(g.campos.find((c) => c.nombre === ruleField)?.texto ?? "").toLowerCase();
      if (regla && rules.has(regla)) warnings.push(`gotchas «${rules.get(regla)}» and «${g.titulo}» state the same rule — merge them?`);
      else if (regla) rules.set(regla, g.titulo);
      for (const r of g.rutas) if (trackedFiles && !isTracked(r, trackedFiles)) warnings.push(`obsolete? gotcha «${g.titulo}» cites \`${r}\`, which git does not track.`);
    }
  }

  // Obsolete and stale: evidence pointing at nothing, and state nobody re-verified in a while.
  const ageDays = (e) => (today - Date.parse(e.ts)) / 86400000;
  for (const [k, e] of state.signals)
    for (const r of rutasCitadas(e.evidence)) if (trackedFiles && !isTracked(r, trackedFiles)) warnings.push(`obsolete? signal «${k}» (#${e.seq}) cites \`${r}\`, which git does not track — \`record signal.retired\` or re-verify.`);
  const stale = [...state.signals].filter(([, e]) => ageDays(e) > STALE_DAYS).sort((a, b) => byTime(a[1], b[1]));
  if (stale.length) warnings.push(`${stale.length} signal(s) not re-verified in more than ${STALE_DAYS} days (oldest: «${stale[0][0]}», ${stale[0][1].ts.slice(0, 10)}) — \`status.mjs log --event signal.verified\`.`);
  const oldDebt = [...state.debt].filter(([, e]) => ageDays(e) > STALE_DAYS);
  if (oldDebt.length) warnings.push(`${oldDebt.length} debt item(s) open for more than ${STALE_DAYS} days — still true? \`record debt.closed\` the ones that are not.`);
  return { errors, warnings, state };
}
const isTracked = (r, files) => (r.endsWith("/") ? files.some((f) => f.startsWith(r)) : files.includes(r));

// ── migration from the legacy STATUS.md ─────────────────────────────────────

/** `git blame` once: for each line, who last wrote it and when. */
function blame(rel) {
  const out = git("blame", "--line-porcelain", "--", rel);
  if (!out) return [];
  const lines = [];
  let cur = {};
  for (const l of out.split("\n")) {
    if (/^[0-9a-f]{40} /.test(l)) cur = {};
    else if (l.startsWith("author ")) cur.author = l.slice(7);
    else if (l.startsWith("author-time ")) cur.time = Number(l.slice(12));
    else if (l.startsWith("\t")) lines.push({ ...cur });
  }
  return lines;
}
const stamp = (bl, from, to = from) => {
  const span = bl.slice(from, to + 1).filter((b) => b.time);
  if (!span.length) return { ts: isoLocal(), author: defaultAuthor() };
  const last = span.reduce((a, b) => (b.time > a.time ? b : a));
  return { ts: isoLocal(new Date(last.time * 1000)), author: last.author };
};
const lineOf = (text, needle, from = 0) => {
  const lines = text.split("\n");
  for (let i = from; i < lines.length; i++) if (lines[i].includes(needle)) return i;
  return -1;
};

function migrate() {
  const text = read(STATUS_FILE);
  if (text === null) die(`${STATUS_REL} does not exist.`);
  if (text.includes(BEGIN)) die(`${STATUS_REL} is already a ledger — nothing to migrate.`);
  const bl = blame(STATUS_REL);
  const events = [];
  const { preambulo, secciones } = seccionesDe(text);
  const sec = (re) => secciones.find((s) => re.test(s.titulo));

  // header → gate.verdict
  const field = (name) => vinetasDe(preambulo).find((v) => sinMarcas(v.texto).startsWith(name));
  const verdict = field(FIELDS.verdict);
  if (verdict) {
    const branch = sinMarcas(field(FIELDS.branch)?.texto ?? "").slice(FIELDS.branch.length).replace(/^:\s*/, "");
    const date = sinMarcas(field(FIELDS.date)?.texto ?? "").slice(FIELDS.date.length).replace(/^:\s*/, "");
    // The date line is the one rewritten on every full gate: its blame is when the verdict was taken.
    const at = stamp(bl, lineOf(text, FIELDS.date));
    const word = /\bROJ[OA]\b/i.test(verdict.texto) ? "ROJO" : /\bVERDE\b/i.test(verdict.texto) ? "VERDE" : sinMarcas(verdict.texto).slice(FIELDS.verdict.length + 1).trim();
    const m = /^(\S+)\s*\(([0-9a-f]{6,40})/.exec(branch);
    events.push({ ...at, ts: /^\d{4}-\d{2}-\d{2}$/.test(date) && !at.ts.startsWith(date) ? `${date}T00:00:00${at.ts.slice(19)}` : at.ts, event: "gate.verdict", key: m?.[1] ?? (branch.split(/\s/)[0] || "main"), what: word, evidence: `migrated from the legacy header «${branch}»${m ? ` @ ${m[2]}` : ""}` });
  }

  // Señales table → signal.verified, each stamped by the blame of its own row.
  const signals = sec(new RegExp(SECTIONS.signals, "i"));
  if (signals) {
    const from = lineOf(text, `## ${signals.titulo}`);
    for (const f of tablaDe(signals.cuerpo)) {
      const [name, command, result] = Object.values(f).map(unescapeCell);
      events.push({ ...stamp(bl, lineOf(text, `| ${name} |`, from)), event: "signal.verified", key: name, what: result ?? "", evidence: command ?? "" });
    }
    for (const para of signals.cuerpo.split(/\n\s*\n/).map((p) => p.trim()).filter((p) => p && !p.startsWith("|")))
      events.push({ ...stamp(bl, lineOf(text, para.split("\n")[0], from)), event: "note", key: "", what: para, evidence: "" });
  }

  // Deuda conocida → debt.opened, keyed by the bold lead of the bullet.
  const debt = sec(new RegExp(SECTIONS.debt, "i"));
  if (debt) {
    const start = lineOf(text, `## ${debt.titulo}`);
    const lines = text.split("\n");
    for (const v of vinetasDe(debt.cuerpo)) {
      const m = /^\*\*(.+?)\*\*\s*(.*)$/.exec(v.texto);
      const key = m ? m[1] : sinMarcas(v.texto).split(/[.:—]/)[0].slice(0, 80);
      const i = lineOf(text, v.texto.slice(0, 30), start);
      let j = i;
      while (j + 1 < lines.length && /^\s+\S/.test(lines[j + 1])) j++;
      events.push({ ...stamp(bl, i, j), event: "debt.opened", key, what: m ? m[2] : v.texto, evidence: "" });
    }
  }

  // Gotchas → incident.recorded: the title and a pointer. The text stays in the register.
  const gText = INCIDENTS_FILE ? read(path.join(REPO_ROOT, INCIDENTS_FILE)) : null;
  if (gText) {
    const gbl = blame(INCIDENTS_FILE);
    const heading = config.incidents.heading ?? "### GOTCHA";
    const glines = gText.split("\n");
    for (const g of leerGotchas(gText, { encabezado: heading, campos: config.incidents.requiredLines })) {
      const i = glines.findIndex((l) => l.startsWith(heading) && l.slice(heading.length).replace(/^:\s*/, "").trim() === g.titulo);
      let j = i;
      while (j + 1 < glines.length && !glines[j + 1].startsWith(heading) && !/^---\s*$/.test(glines[j + 1])) j++;
      events.push({ ...stamp(gbl, i, j), event: "incident.recorded", key: g.titulo, what: "", evidence: `${INCIDENTS_FILE}:${i + 1}` });
    }
  }

  // Chronological, then numbered: the seq is the order things happened in the history we found.
  const order = { "signal.verified": 0, "debt.opened": 1, "incident.recorded": 2, note: 3, "gate.verdict": 4 };
  events.sort((a, b) => byTime(a, b) || order[a.event] - order[b.event]);
  events.forEach((e, i) => (e.seq = i + 1));
  events.push({ seq: events.length + 1, ts: isoLocal(), author: option("--author") ?? defaultAuthor(), event: "note", key: "migration", what: LABELS.migrated(events.length, STATUS_REL, INCIDENTS_FILE ?? "—"), evidence: "`node scripts/status.mjs migrate --apply`" });

  const head = text.split(/^- \*\*/m)[0].trimEnd();
  const counts = Object.entries(events.reduce((a, e) => ((a[e.event] = (a[e.event] ?? 0) + 1), a), {}))
    .map(([k, n]) => `${k} ${n}`)
    .join(" · ");
  if (!flag("--apply")) {
    console.log(`status migrate (dry-run): ${events.length} events from ${STATUS_REL}${INCIDENTS_FILE ? ` + ${INCIDENTS_FILE}` : ""} — ${counts}`);
    for (const e of events.slice(0, 5)) console.log(`  #${e.seq} ${e.ts} ${e.author} ${e.event} ${e.key.slice(0, 60)}`);
    console.log(`  …\nNothing written. \`--apply\` rewrites ${STATUS_REL} (commit it first: git keeps the old one).`);
    return;
  }
  writeStatus(head, events, { fresh: true });
  console.log(`status migrate: ${STATUS_REL} is now a ledger — ${counts}.`);
}

// ── commands ────────────────────────────────────────────────────────────────

function trackedFiles() {
  const out = git("ls-files", "-z");
  return out === null ? null : out.split("\0").filter(Boolean);
}
const gotchasText = () => (INCIDENTS_FILE ? read(path.join(REPO_ROOT, INCIDENTS_FILE)) : null);

switch (cmd) {
  case "migrate":
    migrate();
    break;

  case "record": {
    let [event, key, what] = positionals();
    // A keyless event (`note`) reads `record note "<what>"`: the second word is what happened.
    if (EVENTS[event] && !EVENTS[event].key && what === undefined) [key, what] = ["", key];
    if (!event || !EVENTS[event]) die(`usage: record <event> <key> "<what>" [--evidence "…"] [--author "…"]. Events: ${Object.keys(EVENTS).join(", ")}.`);
    const def = EVENTS[event];
    if (def.key && !key) die(`\`${event}\` needs a key (the signal, debt item or gotcha title it is about).`);
    if (!what && !def.pointer) die(`say what happened: record ${event} "${key}" "<what>".`);
    const st = loadLedger();
    const ingested = ingest(st);
    if (def.closes && !fold(st.events)[{ "signal.verified": "signals", "debt.opened": "debt", "incident.recorded": "incidents" }[def.closes]].has(key))
      die(`«${key}» is not open, so \`${event}\` would close nothing. \`node scripts/status.mjs log --key "${key}"\` shows its history.`);
    const e = { seq: lastSeq(st.events) + 1, ts: isoLocal(), author: option("--author") ?? defaultAuthor(), event, key: def.key ? key : (key ?? ""), what: what ?? "", evidence: option("--evidence") ?? "" };
    st.events.push(e);
    writeStatus(st.head, st.events);
    if (ingested) clearJournal();
    console.log(`status: #${e.seq} ${e.ts} ${e.author} ${event}${e.key ? ` «${e.key}»` : ""}${ingested ? ` (+${ingested} from the gate journal)` : ""}`);
    break;
  }

  case "sync": {
    const st = loadLedger();
    const n = ingest(st);
    if (!n) {
      console.log("status sync: journal empty — nothing to ingest.");
      break;
    }
    writeStatus(st.head, st.events);
    clearJournal();
    console.log(`status sync: ${n} event(s) from the gate are now in ${STATUS_REL}.`);
    break;
  }

  case "rebuild": {
    const st = loadLedger();
    // A merge of two branches leaves two #N: renumber in FILE order, not by time — re-sorting
    // could put a `debt.closed` before its `debt.opened`.
    if (flag("--reseq")) st.events.forEach((e, i) => (e.seq = i + 1));
    writeStatus(st.head, st.events);
    console.log(`status rebuild: projection replayed from ${st.events.length} events.`);
    break;
  }

  case "check": {
    const st = loadStatus();
    const { errors, warnings, state } = validate(st, { gotchasText: gotchasText(), trackedFiles: trackedFiles() });
    for (const w of warnings) console.log(`  ⚠ ${w}`);
    for (const e of errors) console.error(`  ✗ ${e}`);
    if (errors.length) {
      console.error(`status ledger: RED — ${errors.length} problem(s) in ${st.events.length} events.`);
      process.exit(1);
    }
    console.log(`status ledger: ok — ${st.events.length} events, ${state.signals.size} signals, ${state.debt.size} debt, ${state.incidents.size} incidents, ${warnings.length} warning(s).`);
    break;
  }

  case "log": {
    const st = loadLedger();
    const [ev, key, author, since] = ["--event", "--key", "--author", "--since"].map(option);
    const rows = st.events.filter(
      (e) =>
        (!ev || e.event === ev || e.event.startsWith(`${ev}.`)) &&
        (!key || e.key.toLowerCase().includes(key.toLowerCase())) &&
        (!author || e.author.toLowerCase().includes(author.toLowerCase())) &&
        (!since || Date.parse(e.ts) >= Date.parse(since)),
    );
    // With one match the detail is what was asked for: the full row, not a truncated line.
    if (rows.length === 1) {
      const e = rows[0];
      console.log(`#${e.seq}  ${e.ts}  ${e.author}  ${e.event}\n  ${LABELS.logColumns[4]}: ${e.key || "—"}\n  ${LABELS.logColumns[5]}: ${e.what || "—"}\n  ${LABELS.logColumns[6]}: ${e.evidence || "—"}`);
    } else for (const e of rows) console.log(`#${String(e.seq).padStart(4)}  ${e.ts}  ${e.author.padEnd(16)}  ${e.event.padEnd(17)}  ${e.key ? `«${e.key.slice(0, 50)}» ` : ""}${sinMarcas(e.what).slice(0, 100)}`);
    console.log(`(${rows.length} event(s))`);
    break;
  }

  default:
    console.log("usage: node scripts/status.mjs <record|sync|rebuild|check|log|migrate> — see the header of this file.");
    process.exit(cmd ? 1 : 0);
}
